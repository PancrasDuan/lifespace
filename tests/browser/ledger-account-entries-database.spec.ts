import { test, expect } from './authenticated-test'
import { ledgerAccountReceiptSchema, ledgerReceiptSchema } from '../../src/shared/ledger'
import { installLedgerDatabase, ledgerRequest, ledgerRpc } from '../support/ledger-database'

let restore: () => void
let owner: string
let writes: Record<string, unknown>[]
const create = async (name = '银行卡', balanceCents = 100000) => {
  const response = await ledgerRequest(owner, '/api/ledger/accounts', { requestId: crypto.randomUUID(), name, balanceCents })
  expect(response.status).toBe(200)
  return ledgerAccountReceiptSchema.parse(await response.json()).accountId
}
const patch = (id: string, fields: Record<string, unknown>) => ledgerRequest(owner, `/api/ledger/accounts/${id}`, { requestId: crypto.randomUUID(), ...fields }, 'PATCH')
const expense = async (accountId: string) => {
  const response = await ledgerRequest(owner, '/api/ledger/entries', { requestId: crypto.randomUUID(), accountId, direction: 'expense', amountCents: -2000, occurredAt: '2025-01-02T03:04:05Z', categoryCode: 'dining', note: '' })
  expect(response.status).toBe(200)
  return ledgerReceiptSchema.parse(await response.json()).entryId
}
test.describe('正式页面账户流水 → Worker → 隔离数据库', () => {
  test.setTimeout(40000)
  test.skip(!ledgerRpc, '须显式启动隔离数据库，跳过不计通过')
  test.beforeEach(async ({ context }) => {
    restore = installLedgerDatabase(); owner = crypto.randomUUID(); writes = []
    await context.route('**/api/ledger/**', async route => {
      const req = route.request(), url = new URL(req.url()), body = req.method() === 'GET' ? undefined : req.postDataJSON()
      if (body) writes.push(body)
      const response = await ledgerRequest(owner, url.pathname + url.search, body, req.method())
      await route.fulfill({ status: response.status, contentType: 'application/json', body: await response.text() })
    })
  })
  test.afterEach(() => restore?.())

  for (const width of [1440, 390]) test(`${width}px 选择本人账户记录支出、收入和补录，账户与流水刷新持久化`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    const id = await create()
    await page.goto('/finance')
    const form = page.getByRole('dialog', { name: '新建流水', exact: true })
    await page.getByRole('button', { name: '新建流水' }).first().click()
    await form.getByLabel('交易账户', { exact: true }).selectOption(id)
    await form.getByLabel('交易金额', { exact: true }).fill('20')
    await form.getByLabel('交易分类', { exact: true }).selectOption('dining')
    await form.getByLabel('交易时间', { exact: true }).fill('2025-01-02T11:04:05')
    await form.getByRole('button', { name: '保存流水', exact: true }).click()
    await expect(form).toBeHidden()
    await expect(page.getByRole('article', { name: '银行卡', exact: true })).toContainText('980.00')
    expect(writes[0]).toMatchObject({ accountId: id })
    expect(writes[0]).not.toHaveProperty('accountName')
    await page.getByRole('button', { name: '新建流水' }).first().click()
    await form.getByRole('button', { name: '收入', exact: true }).click()
    await form.getByLabel('交易账户', { exact: true }).selectOption(id)
    await form.getByLabel('交易金额', { exact: true }).fill('50')
    await form.getByLabel('交易分类', { exact: true }).selectOption('salary')
    await form.getByRole('button', { name: '保存流水', exact: true }).click()
    await expect(form).toBeHidden()
    await page.reload()
    await expect(page.getByRole('article', { name: '银行卡', exact: true })).toContainText('1,030.00')
    await expect(page.getByRole('table').locator('tbody tr')).toHaveCount(2)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `.cache/ledger120-entries-${width}.png`, fullPage: true })
  })

  test('其他设备改名后详情和列表显示现名，刷新保留表单选定账户和输入', async ({ page }) => {
    const id = await create()
    await expense(id)
    await page.goto('/finance')
    await page.getByRole('table').getByRole('button', { name: '餐饮', exact: true }).click()
    const detail = page.getByRole('dialog', { name: '流水详情', exact: true })
    await expect(detail).toContainText('银行卡')
    expect((await patch(id, { name: '工资卡' })).status).toBe(200)
    await page.evaluate(() => window.dispatchEvent(new Event('focus')))
    await expect(detail).toContainText('工资卡')
    await detail.getByRole('button', { name: '关闭', exact: true }).click()
    await expect(page.getByRole('table')).toContainText('工资卡')
    await page.getByRole('button', { name: '新建流水' }).first().click()
    const form = page.getByRole('dialog', { name: '新建流水', exact: true })
    await form.getByLabel('交易账户', { exact: true }).selectOption(id)
    await form.getByLabel('交易金额', { exact: true }).fill('12.34')
    await form.getByLabel('交易备注').fill('继续填写')
    expect((await patch(id, { name: '现金' })).status).toBe(200)
    await page.evaluate(() => window.dispatchEvent(new Event('focus')))
    await expect(form.getByLabel('交易账户', { exact: true })).toHaveValue(id)
    await expect(form.getByRole('option', { name: '现金', exact: true })).toHaveCount(1)
    await expect(form.getByLabel('交易金额', { exact: true })).toHaveValue('12.34')
    await expect(form.getByLabel('交易备注')).toHaveValue('继续填写')
    await page.screenshot({ path: '.cache/ledger120-account-select.png' })
  })

  test('重新打开详情等待本次读取后才允许退款，避免使用缓存旧额度', async ({ page, context }) => {
    const id = await create(), entryId = await expense(id)
    await page.goto('/finance')
    const detail = page.getByRole('dialog', { name: '流水详情', exact: true })
    await page.getByRole('button', { name: '餐饮', exact: true }).click()
    await expect(detail).toContainText('银行卡')
    await detail.getByRole('button', { name: '关闭', exact: true }).click()
    const response = await ledgerRequest(owner, `/api/ledger/entries/${entryId}/refunds`, { requestId: crypto.randomUUID(), amountCents: 500, occurredAt: '2025-01-03T00:00:00Z', note: '' })
    expect(response.status).toBe(200)
    let release: (() => void) | undefined
    await context.route(`**/api/ledger/entries/${entryId}?*`, async route => {
      await new Promise<void>(done => { release = done })
      await route.fallback()
    })
    try {
      await page.getByRole('button', { name: '餐饮', exact: true }).click()
      await expect.poll(() => !!release).toBe(true)
      await expect(detail.getByRole('button', { name: '登记退款', exact: true })).toBeHidden({ timeout: 1000 })
    } finally { release?.() }
    await detail.getByRole('button', { name: '登记退款', exact: true }).click()
    await expect(page.getByRole('dialog', { name: '登记退款', exact: true })).toContainText('可退 ¥15.00')
  })

  for (const width of [1440, 390]) test(`${width}px 退款沿用父账户，单删退款与父子同删刷新余额`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    const id = await create()
    await expense(id)
    await page.goto('/finance')
    const detail = page.getByRole('dialog', { name: '流水详情', exact: true }), refund = page.getByRole('dialog', { name: '登记退款', exact: true }), deletion = page.getByRole('dialog', { name: '删除流水', exact: true })
    const card = page.getByRole('article', { name: '银行卡', exact: true })
    await page.getByRole('table').getByRole('button', { name: '餐饮', exact: true }).click()
    await detail.getByRole('button', { name: '登记退款', exact: true }).click()
    await expect(refund.getByLabel('交易账户', { exact: true })).toHaveValue('银行卡')
    await expect(refund.getByLabel('交易账户', { exact: true })).not.toBeEditable()
    await refund.getByLabel('交易金额').fill('5')
    await refund.getByRole('button', { name: '保存退款', exact: true }).click()
    await expect(refund).toBeHidden()
    await expect(card).toContainText('985.00')
    await page.getByRole('table').getByRole('row').filter({ hasText: '+¥5.00' }).click()
    await detail.getByRole('button', { name: '删除流水', exact: true }).click()
    await deletion.getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(deletion).toBeHidden()
    await expect(card).toContainText('980.00')
    await page.getByRole('table').getByRole('button', { name: '餐饮', exact: true }).click()
    await detail.getByRole('button', { name: '登记退款', exact: true }).click()
    await refund.getByLabel('交易金额').fill('3')
    await refund.getByRole('button', { name: '保存退款', exact: true }).click()
    await expect(refund).toBeHidden()
    await expect(card).toContainText('983.00')
    await page.getByRole('table').getByRole('row').filter({ hasText: '-¥20.00' }).click()
    await detail.getByRole('button', { name: '删除流水', exact: true }).click()
    await expect(deletion).toContainText('同时删除 1 笔退款')
    await deletion.getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(deletion).toBeHidden()
    await expect(card).toContainText('1,000.00')
    await page.reload()
    await expect(card).toContainText('1,000.00')
    await expect(page.getByRole('region', { name: '账单流水', exact: true })).toContainText('0 条流水')
  })

  test('金额超限提示明确并保留输入，页面和刷新后均无部分入账', async ({ page }) => {
    const id = await create('上限账户', 99999999999)
    await page.goto('/finance')
    await page.getByRole('button', { name: '新建流水' }).first().click()
    const form = page.getByRole('dialog', { name: '新建流水', exact: true })
    await form.getByRole('button', { name: '收入', exact: true }).click()
    await form.getByLabel('交易账户', { exact: true }).selectOption(id)
    await form.getByLabel('交易金额').fill('0.01')
    await form.getByLabel('交易分类', { exact: true }).selectOption('salary')
    await form.getByRole('button', { name: '保存流水', exact: true }).click()
    await expect(form.getByRole('alert')).toContainText('余额超出允许范围')
    await expect(form.getByLabel('交易金额')).toHaveValue('0.01')
    await expect(form.getByLabel('交易金额')).toBeEnabled()
    await page.reload()
    await expect(page.getByRole('article', { name: '上限账户', exact: true })).toContainText('999,999,999.99')
    await expect(page.getByRole('region', { name: '账单流水', exact: true })).toContainText('0 条流水')
  })

  test('未归属旧流水隐藏，账户为空时不能提交且刷新不清除已填金额', async ({ page }) => {
    owner = '12000000-0000-4000-8000-000000000001'
    await page.goto('/finance')
    await expect(page.getByText('暂无流水', { exact: true })).toBeVisible()
    await expect(page.getByText('旧名称保留', { exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: '新建流水' }).first().click()
    const form = page.getByRole('dialog', { name: '新建流水', exact: true })
    await expect(form.getByLabel('交易账户', { exact: true })).toBeDisabled()
    await expect(form.getByRole('button', { name: '保存流水', exact: true })).toBeDisabled()
    await expect(form.getByRole('status')).toContainText('暂无交易账户')
    await form.getByLabel('交易金额').fill('12.34')
    const id = await create('另一设备新增', 0)
    await page.evaluate(() => window.dispatchEvent(new Event('focus')))
    await form.getByLabel('交易账户', { exact: true }).selectOption(id)
    await expect(form.getByLabel('交易金额')).toHaveValue('12.34')
  })
})

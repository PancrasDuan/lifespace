import { test, expect } from './authenticated-test'
import { emptyPlanning, planningFixture, withMainline, withGoal, mainlineId } from './adventure-fixture'

test('人生冒险读取失败时提供重新读取', async ({ page }) => {
  await page.goto('/adventure')
  await expect(page.getByRole('heading', { name: '人生冒险', exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('暂时无法读取人生冒险')
  await expect(page.getByRole('button', { name: '重新读取' })).toBeVisible()
})

test('空规划从一级零经验开始，创建主线后查询并刷新回读', async ({ page, context }) => {
  const server = await planningFixture(context)
  await page.goto('/adventure')
  await expect(page.getByText('Lv.1', { exact: true })).toBeVisible()
  await expect(page.getByText('还没有主线。为长期经营的方向起一个名字。')).toBeVisible()
  server.saved(withMainline)
  await page.getByRole('button', { name: '新建', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '主线', exact: false }).click()
  await page.getByLabel('主线名称').fill('健康')
  await page.getByRole('dialog').getByRole('button', { name: '创建主线', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByRole('article', { name: '主线：健康' })).toBeVisible()
  expect(server.envelopes).toHaveLength(1)
  expect(server.envelopes[0]).toMatchObject({ expectedVersion: 0, command: { type: 'createMainline', name: '健康' } })
  await page.reload()
  await expect(page.getByRole('article', { name: '主线：健康' })).toBeVisible()
})

test('目标归属必须手选，填写标准后持久展示详情，编辑取消无命令', async ({ page, context }) => {
  const server = await planningFixture(context, withMainline)
  server.saved(withGoal)
  await page.goto('/adventure')
  await page.getByRole('button', { name: '创建目标', exact: true }).click()
  await expect(page.getByLabel('目标归属')).toHaveValue('')
  await page.getByLabel('目标名称').fill('五公里')
  await page.getByLabel('完成标准').fill('连续跑完五公里')
  await page.getByLabel('目标归属').selectOption(mainlineId)
  await page.getByRole('dialog').getByRole('button', { name: '创建目标', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  expect(server.envelopes[0].command).toEqual({ type: 'createGoal', destination: mainlineId, title: '五公里', standard: '连续跑完五公里' })
  await page.getByRole('button', { name: '五公里', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('连续跑完五公里')
  await page.getByRole('dialog').getByRole('button', { name: '编辑目标' }).click()
  await page.getByLabel('目标名称').fill('不保存')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  expect(server.envelopes).toHaveLength(1)
  await expect(page.getByRole('button', { name: '五公里', exact: true })).toBeVisible()
})

test('独立目标直接选择独立身份，不展示系统容器或旧操作', async ({ page, context }) => {
  const server = await planningFixture(context)
  server.saved({ ...withGoal, mainlines: [], destinations: emptyPlanning.destinations,
    goals: [{ ...withGoal.goals[0], independent: true, mainlineName: '独立区' }] })
  await page.goto('/adventure')
  await page.getByRole('button', { name: '创建目标', exact: true }).click()
  await page.getByLabel('目标归属').selectOption('independent')
  await page.getByLabel('目标名称').fill('五公里')
  await page.getByLabel('完成标准').fill('连续跑完五公里')
  await page.getByRole('dialog').getByRole('button', { name: '创建目标', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByText('独立目标', { exact: true })).toBeVisible()
  expect(server.envelopes[0].command).toMatchObject({ destination: 'independent' })
  await expect(page.getByText(/支线|次日|周期|inbox|独立区/)).toHaveCount(0)
  await expect(page.getByRole('button', { name: '添加任务' })).toBeDisabled()
})

    await page.goto(`/adventure?taskId=${task}`)
    await expect(page.getByRole('dialog', { name: '任务安排历史', exact: true })).toContainText('2020-01-01')
    await expect(page.getByRole('dialog', { name: '任务安排历史', exact: true })).toContainText('冻结说明')

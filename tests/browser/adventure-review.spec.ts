test('结果未知时保留同一封套，弹窗内安全重试且不重复新建', async ({ page, context }) => {
  const server = await planningFixture(context)
  server.saved(withMainline)
  await page.goto('/adventure?view=planning')
  await page.getByRole('button', { name: '新建', exact: true }).click()
  await page.getByRole('region', { name: '快速新建' }).getByRole('button', { name: '一条主线', exact: true }).click()
  await page.getByLabel('主线名称').fill('健康')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const before = await page.locator('.adventure-proto-workspace').boundingBox()
  server.loseNextResponse()
  await page.getByRole('dialog').getByRole('button', { name: '创建主线', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('button', { name: '安全重试同一次操作' })).toBeVisible()
  const error = page.getByRole('alert')
  await expect(error).toHaveCount(1)
  expect(await error.evaluate(element => getComputedStyle(element).position)).toBe('fixed')
  const after = await page.locator('.adventure-proto-workspace').boundingBox()
  expect(after!.y).toBeCloseTo(before!.y, 1)
  await expect(page.getByLabel('主线名称')).toBeDisabled()
  const retry = page.getByRole('dialog').getByRole('button', { name: '安全重试同一次操作' })
  await retry.focus()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '关闭错误提示' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(retry).toBeVisible()
  await retry.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toBeHidden()
  expect(server.envelopes).toHaveLength(2)
  expect(server.envelopes[1]).toEqual(server.envelopes[0])
})

test('版本冲突重新读取后等待用户再次确认，不自动重放', async ({ page, context }) => {
  const server = await planningFixture(context)
  server.saved(withMainline)
  await page.goto('/adventure?view=planning')
  await page.getByRole('button', { name: '新建', exact: true }).click()
  await page.getByRole('region', { name: '快速新建' }).getByRole('button', { name: '一条主线', exact: true }).click()
  await page.getByLabel('主线名称').fill('职业')
  server.conflictNext()
  await page.getByRole('dialog').getByRole('button', { name: '创建主线', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('再次确认原操作')
  expect(server.envelopes).toHaveLength(1)
  await expect(page.getByLabel('主线名称')).toHaveValue('职业')
  await page.getByRole('dialog').getByRole('button', { name: '创建主线', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  expect(server.envelopes[1].expectedVersion).toBe(1)
  expect(server.envelopes[1].requestId).not.toBe(server.envelopes[0].requestId)
})

test('早于成功版本的查询不能覆盖页面或放行新命令', async ({ page, context }) => {
  const server = await planningFixture(context)
  server.saved(withMainline)
  await page.goto('/adventure?view=planning')
  await page.getByRole('button', { name: '新建', exact: true }).click()
  await page.getByRole('region', { name: '快速新建' }).getByRole('button', { name: '一条主线', exact: true }).click()
  await page.getByLabel('主线名称').fill('健康')
  server.staleQueries(true)
  await page.getByRole('dialog').getByRole('button', { name: '创建主线', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByRole('alert')).toContainText('操作已成功，页面更新失败')
  await expect(page.getByRole('article', { name: '主线：健康' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '新建', exact: true })).toBeDisabled()
  server.staleQueries(false)
  await page.getByRole('button', { name: '重新读取' }).click()
  await expect(page.getByRole('article', { name: '主线：健康' })).toBeVisible()
  expect(server.envelopes).toHaveLength(1)
})

test('命令成功后的查询共享总超时，超时仍明确提示已保存而读取失败', async ({ page, context }) => {
  // Keep the platform timeout semantics, shortening only the 15s UI budget for this regression.
  await context.addInitScript(() => {
    const original = AbortSignal.timeout.bind(AbortSignal)
    AbortSignal.timeout = ms => original(ms === 15_000 ? 1_200 : ms)
  })
  const server = await planningFixture(context)
  server.saved(withMainline)
  await page.goto('/adventure?view=planning')
  await page.getByRole('button', { name: '新建', exact: true }).click()
  await page.getByRole('region', { name: '快速新建' }).getByRole('button', { name: '一条主线', exact: true }).click()
  await page.getByLabel('主线名称').fill('健康')
  server.delayNextCommand(800)
  server.delayNextQuery(800)
  await page.getByRole('dialog').getByRole('button', { name: '创建主线', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByRole('alert')).toContainText('操作已成功，页面更新失败')
  await expect(page.getByRole('button', { name: '新建', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '重新读取' }).click()
  await expect(page.getByRole('article', { name: '主线：健康' })).toBeVisible()
  expect(server.envelopes).toHaveLength(1)
})

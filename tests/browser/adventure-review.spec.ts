test('成功反馈使用浮动 toast，不推挤布局，可自动消失、再次出现及手动关闭', async ({ page, context }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install()
  const server = await planningFixture(context)
  server.saved(withMainline)
  await page.goto('/adventure?view=planning')
  const before = await page.locator('.adventure-proto-workspace').boundingBox()
  await page.getByRole('button', { name: '新建', exact: true }).click()
  await page.getByRole('region', { name: '快速新建' }).getByRole('button', { name: '一条主线', exact: true }).click()
  await page.getByLabel('主线名称').fill('健康')
  await page.getByRole('dialog').getByRole('button', { name: '创建主线', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  const toast = page.getByRole('status').filter({ hasText: '已保存' })
  await expect(toast).toBeVisible()
  expect(await toast.evaluate(element => getComputedStyle(element).position)).toBe('fixed')
  await expect(toast).toHaveCSS('opacity', '1')
  const after = await page.locator('.adventure-proto-workspace').boundingBox()
  expect(after!.y).toBeCloseTo(before!.y, 1)
  await page.screenshot({ path: '.cache/planning-toast.png' })
  await page.clock.fastForward(4_100)
  await expect(toast).toBeHidden()
  server.saved({ ...withMainline, version: 2, mainlines: [{ ...withMainline.mainlines[0], name: '健康与活力' }] })
  await openRecordActions(page.getByRole('article', { name: '主线：' + '健康', exact: true }))
  await page.getByRole('button', { name: '修改主线 健康' }).click()
  await page.getByLabel('主线名称', { exact: true }).fill('健康与活力')
  await page.getByRole('button', { name: '保存名称' }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(toast).toBeVisible()
  await page.getByRole('button', { name: '关闭成功提示' }).click()
  await expect(toast).toBeHidden()
  expect(server.envelopes).toHaveLength(2)
})


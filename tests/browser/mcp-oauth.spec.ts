for (const width of [1440, 390]) {
  test(`${width}px 同意页默认空选、键盘选择、全选与取消全选、明确提交`, async ({ page }) => {
    await page.setViewportSize({ width, height: 980 })
    let submitted: { decision: string; scopes: string[] } | undefined
    let submissions = 0
    await page.route('**/api/oauth/consent/finish', async route => {
      submitted = route.request().postDataJSON()
      submissions++
      await route.fulfill({ json: { redirectTo: 'https://client.example.invalid/callback?code=synthetic-code' } })
    })
    await page.route('https://client.example.invalid/callback**', route => route.fulfill({ body: '已返回合成客户端' }))
    await page.goto('/oauth/authorize?client_id=synthetic')
    await expect(page.getByRole('heading', { name: '授权访问账单' })).toBeVisible()
    await expect(page).toHaveTitle('客户端授权 · LifeSpace')
    const authorization = page.locator('.mcp-authorization')
    await expect(authorization).not.toContainText('Codex')
    await expect(authorization).not.toContainText('client.example.invalid')
    await expect(authorization).not.toContainText('127.0.0.1')
    await expect(authorization.locator('a')).toHaveCount(0)
    const approve = page.getByRole('button', { name: '授权所选权限' })
    const selectionToggle = page.getByRole('button', { name: /^(全选|取消全选)$/ })
    await expect(page.getByRole('checkbox')).toHaveCount(3)
    await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(0)
    await expect(page.getByText('已选 0 项权限', { exact: true })).toBeVisible()
    await expect(approve).toHaveAttribute('disabled', '')
    await page.screenshot({ path: `.cache/mcp-consent-empty-${width}.png`, fullPage: true })
    const read = page.getByRole('checkbox', { name: '读取交易账户' })
    await read.focus()
    await page.keyboard.press('Space')
    await expect(read).toBeChecked()
    await expect(page.getByText('已选 1 项权限', { exact: true })).toBeVisible()
    await expect(approve).toBeEnabled()
    await page.keyboard.press('Space')
    await expect(page.getByText('已选 0 项权限', { exact: true })).toBeVisible()
    await expect(approve).toBeDisabled()
    // Native disabled blocks clicks; a forced form submission still hits the defensive guard.
    await page.locator('.mcp-authorization form').evaluate((form: HTMLFormElement) => form.requestSubmit())
    await expect(page.getByRole('alert')).toContainText('至少选择一项权限')
    await expect(page.getByRole('alert')).toBeFocused()
    expect(submissions).toBe(0)
    await selectionToggle.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(3)
    await expect(page.getByText('已选 3 项权限', { exact: true })).toBeVisible()
    await expect(page.getByRole('alert')).toHaveCount(0)
    await expect(approve).toBeEnabled()
    await expect(selectionToggle).toHaveText('取消全选')
    await page.keyboard.press('Space')
    await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(0)
    await expect(page.getByText('已选 0 项权限', { exact: true })).toBeVisible()
    await expect(approve).toBeDisabled()
    await expect(selectionToggle).toHaveText('全选')
    expect(submissions).toBe(0)
    await selectionToggle.click()
    await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(3)
    await expect(page.getByText('已选 3 项权限', { exact: true })).toBeVisible()
    expect(submissions).toBe(0)
    await page.screenshot({ path: `.cache/mcp-consent-all-${width}.png`, fullPage: true })
    await read.uncheck()
    await expect(selectionToggle).toHaveText('全选')
    await selectionToggle.click()
    await expect(read).toBeChecked()
    await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(3)
    expect(submissions).toBe(0)
    await read.uncheck()
    await page.getByRole('checkbox', { name: '登记退款' }).uncheck()
    await expect(page.getByText('已选 1 项权限', { exact: true })).toBeVisible()
    await page.screenshot({ path: `.cache/mcp-consent-${width}.png`, fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await approve.click()
    await expect(page).toHaveURL(/client\.example\.invalid\/callback/)
    expect(submitted).toMatchObject({ decision: 'approve', scopes: [mcpScopes[1]] })
    expect(submissions).toBe(1)
  })

  test(`${width}px 提交中锁定全部操作、防重复提交并从失败恢复`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    let submissions = 0
    let release: () => void = () => {}
    const pendingResponse = new Promise<void>(resolve => { release = resolve })
    await page.route('**/api/oauth/consent/finish', async route => {
      submissions++
      expect(route.request().postDataJSON()).toMatchObject({ decision: 'approve', scopes: mcpScopes })
      await pendingResponse
      await route.fulfill({ status: 503, json: { error: { message: '暂时无法连接，请稍后重试' } } })
    })
    await page.goto('/oauth/authorize')
    const selectionToggle = page.getByRole('button', { name: /^(全选|取消全选)$/ })
    await selectionToggle.click()
    await page.getByRole('button', { name: '授权所选权限' }).click()
    await expect(page.getByRole('button', { name: '正在处理…' })).toBeDisabled()
    await expect(selectionToggle).toHaveText('取消全选')
    await expect(selectionToggle).toBeDisabled()
    await expect(page.getByRole('button', { name: '拒绝授权' })).toBeDisabled()
    for (const checkbox of await page.getByRole('checkbox').all()) await expect(checkbox).toBeDisabled()
    await page.locator('.mcp-authorization form').evaluate((form: HTMLFormElement) => { form.requestSubmit(); form.requestSubmit() })
    await expect(page.getByText('已选 3 项权限', { exact: true })).toBeVisible()
    expect(submissions).toBe(1)
    release()
    await expect(page.getByRole('alert')).toBeFocused()
    await expect(page.getByRole('alert')).toBeInViewport()
    await expect(selectionToggle).toBeEnabled()
    await expect(page.getByRole('button', { name: '授权所选权限' })).toBeEnabled()
    await expect(page.getByRole('button', { name: '拒绝授权' })).toBeEnabled()
    for (const checkbox of await page.getByRole('checkbox').all()) await checkbox.uncheck()
    await expect(page.getByRole('button', { name: '授权所选权限' })).toBeDisabled()
    await selectionToggle.click()
    await page.getByRole('button', { name: '授权所选权限' }).click()
    await expect(page.getByRole('alert')).toBeFocused()
    expect(submissions).toBe(2)
  })
}


import { test, expect } from './authenticated-test'
import { ledgerAccountReceiptSchema, ledgerAccountsSchema, ledgerPageSchema } from '../../src/shared/ledger'
import { installLedgerDatabase, ledgerRequest, ledgerRpc } from '../support/ledger-database'

let restore: () => void
let owner: string
const account = async (name: string, balanceCents = 0) => {
  const response = await ledgerRequest(owner, '/api/ledger/accounts', { requestId: crypto.randomUUID(), name, balanceCents })
  expect(response.status).toBe(200)
  return ledgerAccountReceiptSchema.parse(await response.json()).accountId
}
test.describe('正式转账页面 → Worker → 隔离数据库', () => {
  test.setTimeout(40000)
  test.skip(!ledgerRpc, '须显式启动隔离数据库，跳过不计通过')
  test.beforeEach(async ({ context }) => {
    restore = installLedgerDatabase(); owner = crypto.randomUUID()
    await context.route('**/api/ledger/**', async route => {
      const request = route.request(), url = new URL(request.url())
      const response = await ledgerRequest(owner, url.pathname + url.search, request.method() === 'GET' ? undefined : request.postDataJSON(), request.method())
      await route.fulfill({ status: response.status, contentType: 'application/json', body: await response.text() })
    })
  })
  test.afterEach(() => restore?.())

  for (const width of [1440, 390]) test(`${width}px 完成转账、双向查看关联并整组删除，两侧余额持久化`, async ({ page }) => {
    const from = await account('银行卡'), to = await account('饭卡', -500)
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/finance')
    await page.getByRole('button', { name: '账户转账', exact: true }).click()
    const form = page.getByRole('dialog', { name: '账户转账', exact: true })
    await form.getByLabel('转出账户', { exact: true }).selectOption(from)
    await form.getByLabel('转入账户', { exact: true }).selectOption(to)
    await form.getByLabel('转账金额', { exact: true }).fill('100')
    await form.getByLabel('交易时间', { exact: true }).fill('2025-01-02T11:04:05')
    await form.getByLabel('交易备注', { exact: true }).fill('饭卡充值')
    await page.screenshot({ path: `.cache/ledger121-form-${width}.png` })
    await form.getByRole('button', { name: '确认转账', exact: true }).click()
    await expect(form).toBeHidden()
    await expect(page.getByRole('article', { name: '银行卡', exact: true })).toContainText('-100.00')
    await expect(page.getByRole('article', { name: '饭卡', exact: true })).toContainText('95.00')
    await page.reload()
    await page.getByRole('button', { name: '转出', exact: true }).click()
    const detail = page.getByRole('dialog', { name: '流水详情', exact: true })
    await expect(detail.getByRole('region', { name: '关联转账', exact: true })).toBeVisible()
    await expect(detail.getByRole('button', { name: '登记退款', exact: true })).toHaveCount(0)
    await page.screenshot({ path: `.cache/ledger121-detail-${width}.png` })
    await detail.getByRole('button', { name: '查看关联转入', exact: false }).click()
    await expect(detail).toContainText('饭卡')
    await detail.getByRole('button', { name: '查看关联转出', exact: false }).click()
    await detail.getByRole('button', { name: '删除整笔转账', exact: true }).click()
    const deletion = page.getByRole('dialog', { name: '删除流水', exact: true })
    await expect(deletion).toContainText('银行卡')
    await expect(deletion).toContainText('饭卡')
    await expect(deletion).toContainText('两条关联流水将同时删除')
    await page.screenshot({ path: `.cache/ledger121-delete-${width}.png` })
    await deletion.getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(deletion).toBeHidden()
    await expect(page.getByRole('article', { name: '银行卡', exact: true })).toContainText('0.00')
    await expect(page.getByRole('article', { name: '饭卡', exact: true })).toContainText('-5.00')
    await page.reload()
    await expect(page.getByRole('region', { name: '账单流水', exact: true })).toContainText('0 条流水')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  })

  test('响应丢失冻结原转账，关闭后页内重试不重复扣款', async ({ page }) => {
    const from = await account('银行卡', 100000), to = await account('饭卡')
    const commands: unknown[] = []
    await page.route('**/api/ledger/transfers', async route => {
      const body = route.request().postDataJSON()
      commands.push(body)
      const response = await ledgerRequest(owner, '/api/ledger/transfers', body)
      expect(response.status).toBe(200)
      if (commands.length === 1) await route.abort('failed')
      else await route.fulfill({ status: response.status, contentType: 'application/json', body: await response.text() })
    })
    await page.goto('/finance')
    await page.getByRole('button', { name: '从银行卡转账', exact: true }).click()
    const form = page.getByRole('dialog', { name: '账户转账', exact: true })
    await expect(form.getByLabel('转出账户', { exact: true })).toHaveValue(from)
    await form.getByLabel('转入账户', { exact: true }).selectOption(to)
    await form.getByLabel('转账金额', { exact: true }).fill('20')
    await form.getByRole('button', { name: '确认转账', exact: true }).click()
    await expect(form.getByRole('alert')).toContainText('保存结果未确认')
    await expect(form.getByLabel('转账金额', { exact: true })).toBeDisabled()
    await form.getByRole('button', { name: '关闭', exact: true }).click()
    await page.getByRole('button', { name: '新建流水', exact: true }).first().click()
    const later = page.getByRole('dialog', { name: '新建流水', exact: true })
    await later.getByLabel('交易金额', { exact: true }).fill('12.34')
    // The modal blocks the page banner. Close it, then retry the frozen command.
    await later.getByRole('button', { name: '关闭', exact: true }).click()
    await page.getByRole('button', { name: '重试原请求', exact: true }).click()
    await expect(page.getByRole('article', { name: '银行卡', exact: true })).toContainText('980.00')
    expect(commands).toHaveLength(2)
    expect(commands[1]).toEqual(commands[0])
    expect(ledgerPageSchema.parse(await (await ledgerRequest(owner)).json())).toMatchObject({ total: 2, version: 3 })
    await page.reload()
    await expect(page.getByRole('button', { name: '重试原请求', exact: true })).toHaveCount(0)
  })

  test('账户不足提示、刷新保留输入，余额变化导致的超限拒绝保留表单', async ({ page }) => {
    const from = await account('银行卡', 1000)
    await page.goto('/finance')
    await page.getByRole('button', { name: '账户转账', exact: true }).click()
    const form = page.getByRole('dialog', { name: '账户转账', exact: true })
    await expect(form.getByRole('button', { name: '确认转账', exact: true })).toBeDisabled()
    await expect(form.getByRole('status')).toContainText('两个不同的本人账户')
    await form.getByLabel('转账金额', { exact: true }).fill('20')
    const to = await account('饭卡')
    await page.evaluate(() => window.dispatchEvent(new Event('focus')))
    await form.getByLabel('转出账户', { exact: true }).selectOption(from)
    await form.getByLabel('转入账户', { exact: true }).selectOption(to)
    await expect(form.getByLabel('转账金额', { exact: true })).toHaveValue('20')
    await ledgerRequest(owner, `/api/ledger/accounts/${to}`, { requestId: crypto.randomUUID(), balanceCents: 99999999999, expectedBalanceCents: 0 }, 'PATCH')
    await form.getByRole('button', { name: '确认转账', exact: true }).click()
    await expect(form.getByRole('alert')).toContainText('余额超出允许范围')
    await expect(form.getByLabel('转账金额', { exact: true })).toHaveValue('20')
    await expect(form.getByLabel('转账金额', { exact: true })).toBeEnabled()
    expect(ledgerPageSchema.parse(await (await ledgerRequest(owner)).json()).total).toBe(0)
    expect(ledgerAccountsSchema.parse(await (await ledgerRequest(owner, '/api/ledger/accounts')).json())).toMatchObject({ version: 3 })
  })
})
